-- Development schema is applied with Replit database tools.
-- Review/apply the corresponding production schema changes when publishing.
ALTER TABLE public.vata_accounts ADD COLUMN IF NOT EXISTS subscription_tier text NOT NULL DEFAULT 'free';
ALTER TABLE public.vata_accounts ADD COLUMN IF NOT EXISTS subscription_expires_at timestamptz;
CREATE TABLE IF NOT EXISTS public.vata_scan_usage (
  account_id integer REFERENCES public.vata_accounts(id) ON DELETE CASCADE,
  month date NOT NULL, scans integer NOT NULL DEFAULT 0 CHECK(scans>=0),
  PRIMARY KEY(account_id,month)
);
CREATE TABLE IF NOT EXISTS public.vata_memberships (
  user_id text PRIMARY KEY, account_id integer NOT NULL REFERENCES public.vata_accounts(id) ON DELETE CASCADE,
  label text NOT NULL, joined_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.vata_team_invites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES public.vata_accounts(id) ON DELETE CASCADE,
  token_hash text UNIQUE NOT NULL, expires_at timestamptz NOT NULL, used_at timestamptz, revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.vata_api_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES public.vata_accounts(id) ON DELETE CASCADE,
  user_id text NOT NULL, name text NOT NULL, token_hash text UNIQUE NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), last_used_at timestamptz, revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.vata_scan_schedules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id integer NOT NULL REFERENCES public.vata_accounts(id) ON DELETE CASCADE,
  created_by text NOT NULL, target_url text NOT NULL,
  frequency text NOT NULL CHECK(frequency IN ('once','hourly','daily','weekly')),
  next_run_at timestamptz NOT NULL, enabled boolean NOT NULL DEFAULT true, lease_until timestamptz,
  last_run_at timestamptz, last_error text, created_at timestamptz NOT NULL DEFAULT now()
);
